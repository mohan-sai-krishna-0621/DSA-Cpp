#include <iostream>
using namespace std;

int main() {
    int number = 10;
    float price = 99.50;
    double salary = 25000.75;
    char grade = 'A';
    bool isStudent = true;

    cout << "Integer: " << number << endl;
    cout << "Float: " << price << endl;
    cout << "Double: " << salary << endl;
    cout << "Character: " << grade << endl;
    cout << "Boolean: " << isStudent << endl;

    return 0;
}
